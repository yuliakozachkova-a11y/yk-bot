def main():
    # 1. Удаляем все старые автогенерированные посты первой недели (idempotent re-run)
    import sqlite3
    from bot import config
    con = sqlite3.connect(config.DB_PATH)
    con.execute(
        "DELETE FROM posts WHERE source IN ('manual','youtube') AND scheduled_at >= '2026-05-20' AND scheduled_at < '2026-05-27' AND metadata LIKE '%auto_generated%'"
    )
    con.commit()
    con.close()

    inserted = 0
    for post in POSTS:
        post_id = db.add_post(
            scheduled_at=post["scheduled_at"],
            text=post.get("text", ""),
            media_type="none",
            poll_question=post.get("poll_question"),
            poll_options=post.get("poll_options"),
            source=post.get("source", "manual"),
            genre=post.get("genre", "general"),
            metadata={"week": 1, "auto_generated": True},
        )
        if post.get("status") == "paused":
            db.pause_post(post_id)
        inserted += 1
        local = datetime.fromisoformat(post["scheduled_at"].replace("Z", "+00:00")).astimezone(TZ)
        print(f"  #{post_id} · {local.strftime('%a %d.%m %H:%M')} · {post.get('genre'):<18s} · {post.get('status'):<10s}")

    print(f"\n✅ Inserted: {inserted} posts")
    db.log_event("seed_week1_v2", {"inserted": inserted})


if __name__ == "__main__":
    main()
